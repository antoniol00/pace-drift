code_5 = [
    "class RollingF1:\n",
    "    def __init__(self, window_size=5000, pos_label=\"ATTACK\"):\n",
    "        self.window = deque(maxlen=window_size)\n",
    "        self.pos_label = pos_label\n",
    "    \n",
    "    def update(self, y_true, y_pred):\n",
    "        self.window.append((y_true, y_pred))\n",
    "    \n",
    "    def get(self):\n",
    "        if len(self.window) < 100: return 0.0\n",
    "        tp = fp = fn = 0\n",
    "        for yt, yp in self.window:\n",
    "            if yp == self.pos_label and yt == self.pos_label: tp += 1\n",
    "            elif yp == self.pos_label and yt != self.pos_label: fp += 1\n",
    "            elif yp != self.pos_label and yt == self.pos_label: fn += 1\n",
    "        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0\n",
    "        recall    = tp / (tp + fn) if (tp + fn) > 0 else 0.0\n",
    "        if precision + recall == 0: return 0.0\n",
    "        return 2 * precision * recall / (precision + recall)\n"
]
cells.append({"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": code_5})

code_6 = [
    "# ════════════════════════════════════════════════════════════════\n",
    "# 🧠  Definición del DriftGAN (Simulación de Concept Drift)\n",
    "# ════════════════════════════════════════════════════════════════\n",
    "class DriftGAN:\n",
    "    def __init__(self, input_dim, noise_dim=16, epochs=30, lr=0.005):\n",
    "        self.input_dim = input_dim\n",
    "        self.noise_dim = noise_dim\n",
    "        self.epochs = epochs\n",
    "        \n",
    "        # Generador muy ligero para no penalizar el tiempo de ejecución en el stream\n",
    "        self.generator = nn.Sequential(\n",
    "            nn.Linear(noise_dim, 32),\n",
    "            nn.ReLU(),\n",
    "            nn.Linear(32, input_dim)\n",
    "        )\n",
    "        self.discriminator = nn.Sequential(\n",
    "            nn.Linear(input_dim, 32),\n",
    "            nn.ReLU(),\n",
    "            nn.Linear(32, 1),\n",
    "            nn.Sigmoid()\n",
    "        )\n",
    "        self.opt_g = optim.Adam(self.generator.parameters(), lr=lr)\n",
    "        self.opt_d = optim.Adam(self.discriminator.parameters(), lr=lr)\n",
    "        self.criterion = nn.BCELoss()\n",
    "        \n",
    "    def train_and_generate(self, data_buffer, num_samples=200):\n",
    "        \"\"\"\n",
    "        Entrena la GAN con un buffer de muestras de ataque y genera `num_samples` variaciones sintéticas.\n",
    "        \"\"\"\n",
    "        if len(data_buffer) < 5:\n",
    "            return [] # No hay suficientes datos representativos del nuevo ataque\n",
    "            \n",
    "        keys = list(data_buffer[0].keys())\n",
    "        tensor_data = torch.tensor([[d[k] for k in keys] for d in data_buffer], dtype=torch.float32)\n",
    "        batch_size = tensor_data.size(0)\n",
    "        \n",
    "        # Entrenamiento Rápido\n",
    "        for _ in range(self.epochs):\n",
    "            # Discriminador\n",
    "            self.opt_d.zero_grad()\n",
    "            real_labels = torch.ones(batch_size, 1)\n",
    "            fake_labels = torch.zeros(batch_size, 1)\n",
    "            \n",
    "            outputs = self.discriminator(tensor_data)\n",
    "            d_loss_real = self.criterion(outputs, real_labels)\n",
    "            \n",
    "            z = torch.randn(batch_size, self.noise_dim)\n",
    "            fake_data = self.generator(z)\n",
    "            outputs = self.discriminator(fake_data.detach())\n",
    "            d_loss_fake = self.criterion(outputs, fake_labels)\n",
    "            \n",
    "            d_loss = d_loss_real + d_loss_fake\n",
    "            d_loss.backward()\n",
    "            self.opt_d.step()\n",
    "            \n",
    "            # Generador\n",
    "            self.opt_g.zero_grad()\n",
    "            z = torch.randn(batch_size, self.noise_dim)\n",
    "            fake_data = self.generator(z)\n",
    "            outputs = self.discriminator(fake_data)\n",
    "            g_loss = self.criterion(outputs, real_labels)\n",
    "            \n",
    "            g_loss.backward()\n",
    "            self.opt_g.step()\n",
    "            \n",
    "        # Generación de Muestras Sintéticas\n",
    "        z = torch.randn(num_samples, self.noise_dim)\n",
    "        with torch.no_grad():\n",
    "            synthetic_data = self.generator(z)\n",
    "            \n",
    "        generated = []\n",
    "        for i in range(num_samples):\n",
    "            sample = {k: float(synthetic_data[i, j]) for j, k in enumerate(keys)}\n",
    "            generated.append(sample)\n",
    "            \n",
    "        return generated\n",
    "\n",
    "print(\"✅ DriftGAN definido correctamente.\")\n"
]
