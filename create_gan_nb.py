    "            \n",
    "            # Generar variaciones sintéticas\n",
    "            synthetic_attacks = drift_gan.train_and_generate(attack_samples, num_samples=200)\n",
    "            num_syn = len(synthetic_attacks)\n",
    "            \n",
    "            # Reentrenar el modelo inmediatamente con las variaciones (simulación del concepto)\n",
    "            for syn_x in synthetic_attacks:\n",
    "                model_gan.learn_one(syn_x, \"ATTACK\")\n",
    "                \n",
    "        if n_drifts <= 30:\n",
